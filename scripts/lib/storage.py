#!/usr/bin/env python3
"""Retire fixed disk mounts created by previous versions of the installer."""
import os
from pathlib import Path
import subprocess

from desktop_locale import write_file

FSTAB = Path('etc/fstab')
STORAGE_CONFIG = Path('etc/ubuntu-autoconfig/storage.json')
UDISKS_OPTIONS = Path('etc/udisks2/mount_options.conf')
BEGIN = '# BEGIN ubuntu-autoconfig data volumes'
END = '# END ubuntu-autoconfig data volumes'
LEGACY_OVERRIDE = '[defaults]\nntfs_drivers = ntfs,ntfs3'


def without_managed_volumes(text):
    lines = []
    inside = False
    for line in text.splitlines(keepends=True):
        marker = line.rstrip('\r\n')
        if marker == BEGIN and not inside:
            inside = True
        elif marker == END and inside:
            inside = False
        elif marker in (BEGIN, END):
            raise ValueError('旧 fstab 管理区块的标记不匹配，无法安全清理。')
        elif not inside:
            lines.append(line)
    if inside:
        raise ValueError('旧 fstab 管理区块缺少结束标记，无法安全清理。')
    return ''.join(lines)


def legacy_storage_present(root=Path('/')):
    config = root / STORAGE_CONFIG
    if config.exists() or config.is_symlink():
        return True
    fstab = root / FSTAB
    return fstab.is_file() and bool({BEGIN, END}.intersection(fstab.read_text().splitlines()))


def remove_legacy_storage(root=Path('/')):
    if not legacy_storage_present(root):
        return False

    fstab = root / FSTAB
    original = fstab.read_text() if fstab.is_file() else ''
    remaining = without_managed_volumes(original)
    if remaining != original:
        write_file(fstab, remaining)

    # Remove only the standalone override generated by the old installer.
    # A file containing other UDisks settings belongs to the administrator.
    options = root / UDISKS_OPTIONS
    if options.is_file() and not options.is_symlink() and options.read_text().strip() == LEGACY_OVERRIDE:
        options.unlink()

    if root == Path('/') and Path('/run/systemd/system').is_dir():
        subprocess.run(['systemctl', 'daemon-reload'], check=True, timeout=30)
    (root / STORAGE_CONFIG).unlink(missing_ok=True)
    return True


if __name__ == '__main__':
    if os.geteuid() != 0:
        raise SystemExit('清理旧挂载配置需要 root。')
    try:
        if remove_legacy_storage():
            print('已清除旧版安装器的固定磁盘挂载配置。')
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        raise SystemExit(f'清理旧挂载配置失败: {exc}') from None
